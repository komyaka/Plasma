// ============================================================================
// filter.js — Быстрый поиск по таблице (фильтрация строк)
// ============================================================================
// При вводе текста в поле #myInput фильтрует строки таблицы #myTable:
// показывает только те строки, которые содержат введённый текст.
// Используется jQuery для привязки события и фильтрации.
// ============================================================================

$(document).ready(function () {
    /**
     * Обработчик ввода текста в поле быстрого поиска.
     * Каждая строка <tr> в <tbody id="myTable"> проверяется:
     * если текст строки содержит введённое значение — строка отображается,
     * иначе — скрывается.
     */
    $("#myInput").on("keyup", function () {
        var value = $(this).val().toLowerCase();
        $("#myTable tr").filter(function () {
            $(this).toggle($(this).text().toLowerCase().indexOf(value) > -1);
        });
    });
});
